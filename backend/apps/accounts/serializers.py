class MeSerializer(UserSummarySerializer):
    """Profile: only explicitly allowed fields are writable; anything else is rejected, not ignored."""

    WRITABLE_BY_ROLE = {
        Role.STUDENT: {"phone"},
        Role.LIBRARY: {"full_name", "phone"},
        Role.ADMIN: {"full_name", "phone"},
    }

    full_name = serializers.CharField(max_length=200, required=False)
    phone = serializers.CharField(max_length=30, required=False, allow_blank=True)

    class Meta(UserSummarySerializer.Meta):
        read_only_fields = [f for f in UserSummarySerializer.Meta.fields if f not in ("full_name", "phone")]

    def to_internal_value(self, data):
        allowed = self.WRITABLE_BY_ROLE[self.instance.role]
        forbidden = sorted(set(data) - allowed) if hasattr(data, "keys") else []
        if forbidden:
            raise serializers.ValidationError(
                {field: [_("This field cannot be modified.")] for field in forbidden}, code="protected_field"
            )
        return super().to_internal_value(data)


