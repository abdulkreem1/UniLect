class DeviceInfoSerializer(serializers.Serializer):
    installation_id = serializers.RegexField(
        INSTALLATION_ID_RE,
        write_only=True,
        help_text="Random per-installation id generated by the app and kept in Keystore/Keychain "
        "(16-128 chars, [A-Za-z0-9_-]). Must also be sent as X-Device-ID on every request.",
    )
    platform = serializers.ChoiceField(choices=Platform.choices)
    model = serializers.CharField(max_length=100, required=False, allow_blank=True, default="")
    app_version = serializers.CharField(max_length=30, required=False, allow_blank=True, default="")

    @staticmethod
    def to_device_info(data: dict) -> device_services.DeviceInfo:
        return device_services.DeviceInfo(
            installation_id_hash=hash_installation_id(data["installation_id"]),
            platform=data["platform"],
            model_name=data["model"],
            app_version=data["app_version"],
        )


class LoginSerializer(serializers.Serializer):
    """Identify with ``email`` OR with ``student_number`` + ``university``."""

    email = serializers.EmailField(required=False)
    student_number = serializers.CharField(required=False, max_length=50)
    university = serializers.IntegerField(required=False, min_value=1)
    password = serializers.CharField(write_only=True, trim_whitespace=False, max_length=128)
    device = DeviceInfoSerializer(required=False)

    def validate(self, attrs):
        has_email = bool(attrs.get("email"))
        has_number = bool(attrs.get("student_number"))
        if has_email == has_number:
            raise serializers.ValidationError(_("Provide either an email or a student number, not both."))
        if has_number and not attrs.get("university"):
            raise serializers.ValidationError(
                {"university": _("University is required with a student number.")}
            )
        return attrs

    @property
    def identifier(self) -> str:
        d = self.validated_data
        return d.get("email") or f"{d.get('university')}:{d.get('student_number')}"

    def device_info(self) -> device_services.DeviceInfo | None:
        device = self.validated_data.get("device")
        return DeviceInfoSerializer.to_device_info(device) if device else None


