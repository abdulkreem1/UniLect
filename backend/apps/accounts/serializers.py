class AdminUserSerializer(serializers.ModelSerializer):
    password = serializers.CharField(
        write_only=True,
        required=False,
        trim_whitespace=False,
        max_length=128,
        help_text="Required on creation. The user must change it at first login "
        "unless must_change_password=false.",
    )
    university = serializers.PrimaryKeyRelatedField(
        queryset=University.objects.all(), required=False, allow_null=True
    )
    library = serializers.PrimaryKeyRelatedField(
        queryset=Library.objects.all(), required=False, allow_null=True
    )
    student_number = serializers.CharField(max_length=50, required=False, allow_null=True, allow_blank=False)
    must_change_password = serializers.BooleanField(required=False, default=True)
    active_device = serializers.SerializerMethodField()
    university_name = serializers.CharField(source="university.name", read_only=True, default=None)
    library_name = serializers.CharField(source="library.name", read_only=True, default=None)

    class Meta:
        model = User
        fields = [
            "id",
            "email",
            "full_name",
            "phone",
            "role",
            "student_number",
            "university",
            "university_name",
            "library",
            "library_name",
            "is_active",
            "must_change_password",
            "password",
            "active_device",
            "date_joined",
            "last_login",
            "updated_at",
        ]
        read_only_fields = ["is_active", "date_joined", "last_login", "updated_at"]
        # Role-dependent uniqueness is validated explicitly in validate(); DRF's auto-generated
        # validator for the conditional unique constraint would wrongly require student fields.
        validators = []

    def get_active_device(self, obj) -> dict | None:
        devices = getattr(obj, "active_devices", None)
        if devices is None:
            devices = [d for d in obj.devices.all() if d.status == StudentDevice.Status.ACTIVE]
        return AdminDeviceSerializer(devices[0]).data if devices else None

    def validate_email(self, value: str) -> str:
        value = value.strip().lower()
        qs = User.objects.filter(email__iexact=value)
        if self.instance is not None:
            qs = qs.exclude(pk=self.instance.pk)
        if qs.exists():
            raise serializers.ValidationError(_("A user with this email already exists."))
        return value

    def validate(self, attrs):
        instance = self.instance
        if instance is None and not attrs.get("password"):
            raise serializers.ValidationError({"password": _("This field is required.")})
        if instance is not None and "password" in attrs:
            raise serializers.ValidationError({"password": _("Use the set-password action.")})

        def current(field):
            return attrs[field] if field in attrs else getattr(instance, field, None)

        role = current("role")
        request = self.context["request"]
        if instance is not None and instance.pk == request.user.pk and role != instance.role:
            raise serializers.ValidationError({"role": _("You cannot change your own role.")})

        errors = {}
        if role == Role.STUDENT:
            if not current("student_number"):
                errors["student_number"] = _("Required for students.")
            if current("university") is None:
                errors["university"] = _("Required for students.")
            attrs["library"] = None
        elif role == Role.LIBRARY:
            if current("library") is None:
                errors["library"] = _("Required for library accounts.")
            attrs["student_number"] = None
            attrs["university"] = None
        else:
            attrs["student_number"] = None
            attrs["university"] = None
            attrs["library"] = None
        if errors:
            raise serializers.ValidationError(errors)

        if role == Role.STUDENT:
            dup = User.objects.filter(
                student_number=current("student_number"), university=current("university")
            )
            if instance is not None:
                dup = dup.exclude(pk=instance.pk)
            if dup.exists():
                raise serializers.ValidationError(
                    {"student_number": _("This student number already exists in this university.")}
                )

        if attrs.get("password"):
            candidate = User(email=current("email") or "", full_name=current("full_name") or "", role=role)
            validate_password(attrs["password"], candidate)
        return attrs


